#!/usr/bin/env node
// Reads data/*.json and writes client/src/data/staticData.js so the static
// GitHub Pages build ships with the latest fetched data baked in.

const fs = require('fs')
const path = require('path')

const DATA = path.join(__dirname, '../data')
const OUTPUT = path.join(__dirname, '../client/src/data/staticData.js')

function read(file, fallback) {
  try { return JSON.parse(fs.readFileSync(path.join(DATA, file), 'utf8')) }
  catch { return fallback }
}

const tasks = read('tasks.json', [])
const calendar = read('calendar.json', { events: [] })
const inventory = read('inventory.json', { tabs: [] })
const clients = read('clients.json', { products: [] })

const staticData = {
  generatedAt: new Date().toISOString(),
  tasks,
  calendar: calendar.events || [],
  inventory,
  clients,
}

const output = `// AUTO-GENERATED by scripts/generate-static-data.js — do not edit by hand.
// Generated: ${new Date().toISOString()}
const staticData = ${JSON.stringify(staticData, null, 2)}

export default staticData
`

fs.writeFileSync(OUTPUT, output)
console.log(`[generate] wrote ${OUTPUT}`)
console.log(`  tasks:     ${tasks.length}`)
console.log(`  calendar:  ${(calendar.events || []).length}`)
console.log(`  inventory: ${(inventory.tabs || []).length} tabs, ${(inventory.tabs || []).reduce((n, t) => n + (t.rows?.length || 0), 0)} rows`)
console.log(`  clients:   ${(clients.products || []).length} products`)
